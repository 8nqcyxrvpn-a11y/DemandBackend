def forecast_product(
    base_forecast,
    trend_growth_pct,
    brand_fit_score,
    demand_volatility,
    safety_stock,
    trend_name,
    product_name,
    product_category
):
    # Cap extreme trend growth
    capped_trend_growth = min(max(trend_growth_pct, -50), 100)

    # Trend effect
    trend_factor = 1 + (capped_trend_growth / 100) * 0.08

    # Brand-fit effect
    brand_fit_factor = 1 + ((brand_fit_score - 50) / 50) * 0.05

    # Volatility effect
    volatility_ratio = demand_volatility / max(base_forecast, 1)

    volatility_factor = max(
        0.90,
        1 - volatility_ratio * 0.25
    )

    # Final demand forecast
    forecast = (
        base_forecast
        * trend_factor
        * brand_fit_factor
        * volatility_factor
    )

    # Inventory recommendation
    inventory = forecast + safety_stock

    return {
        "trend": trend_name,
        "product": product_name,
        "category": product_category,
        "forecast_units": round(forecast),
        "recommended_inventory": round(inventory),
        "trend_factor": round(trend_factor, 3),
        "brand_fit_factor": round(brand_fit_factor, 3),
        "volatility_factor": round(volatility_factor, 3)
    }

